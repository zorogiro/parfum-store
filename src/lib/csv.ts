/**
 * CSV helpers for the admin export. Pure module.
 * - Delimiter is ";" (French Excel default); every cell containing the delimiter, a comma, a
 *   quote or a line break is quoted, quotes are doubled.
 * - Formula injection guard: a TEXT cell starting with = + - @ tab or carriage return is
 *   prefixed with a single quote so spreadsheets never evaluate it.
 */

export const CSV_DELIMITER = ";";
export const CSV_BOM = "﻿";

const FORMULA_START = /^[=+\-@\t\r]/;

/** Neutralizes spreadsheet formulas in a text value. */
export function neutralizeFormula(text: string): string {
  return FORMULA_START.test(text) ? `'${text}` : text;
}

/** Escapes one cell. Numbers are written as is (they are generated by us, never user text). */
export function csvCell(value: string | number | null | undefined): string {
  if (value === null || value === undefined) return "";
  const text = typeof value === "number" ? String(value) : neutralizeFormula(value);
  return /[";\r\n,]/.test(text) ? `"${text.replace(/"/g, '""')}"` : text;
}

export function csvRow(cells: ReadonlyArray<string | number | null | undefined>): string {
  return cells.map(csvCell).join(CSV_DELIMITER);
}

/** Full file content: BOM + CRLF-separated rows (RFC 4180 line endings). */
export function toCsv(
  header: readonly string[],
  rows: ReadonlyArray<ReadonlyArray<string | number | null | undefined>>,
): string {
  return CSV_BOM + [csvRow(header), ...rows.map(csvRow)].join("\r\n") + "\r\n";
}
